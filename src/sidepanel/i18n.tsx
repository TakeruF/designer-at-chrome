type Vars = Record<string, string | number>;
type I18nValue = { locale: SupportedLocale; t: (key: string, vars?: Vars) => string };
const I18nContext = createContext<I18nValue | null>(null);

export function translate(locale: SupportedLocale, key: string, vars: Vars = {}): string {
  const dictionary: Record<string, string> = messages[locale];
  const fallback: Record<string, string> = messages.en;
  const template = dictionary[key] ?? fallback[key] ?? key;
  return Object.entries(vars).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    template,
  );
}

export function I18nProvider({ locale, children }: PropsWithChildren<{ locale: SupportedLocale }>) {
  const value = useMemo<I18nValue>(
    () => ({ locale, t: (key, vars) => translate(locale, key, vars) }),
    [locale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider.');
  return value;
}

export function categoryLabel(category: BookmarkCategory | 'All', locale: SupportedLocale): string {
  if (category === 'All') return translate(locale, 'library.all');
  const ja: Record<BookmarkCategory, string> = {
    Header: 'ヘッダー',
    Hero: 'ヒーロー',
    Navigation: 'ナビゲーション',
    Button: 'ボタン',
    Card: 'カード',
    Form: 'フォーム',
    Modal: 'モーダル',
    Footer: 'フッター',
    Typography: 'タイポグラフィ',
    Other: 'その他',
  };
  return locale === 'ja' ? ja[category] : category;
}

export function captureModeLabel(mode: VideoCaptureMode, locale: SupportedLocale): string {
  const key: Record<VideoCaptureMode, string> = {
    'current-frame': 'save.currentFrame',
    'video-player': 'save.player',
    'selected-element': 'save.selected',
  };
  return translate(locale, key[mode]);
}
